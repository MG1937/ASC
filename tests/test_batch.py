from pathlib import Path
import subprocess
import sys
import tempfile
import unittest
import zipfile

from dex_fixture import make_dex, make_static_field_dex


ROOT = Path(__file__).resolve().parents[1]


class BatchTests(unittest.TestCase):
    def setUp(self):
        directory = tempfile.TemporaryDirectory()
        self.addCleanup(directory.cleanup)
        self.work = Path(directory.name)
        self.apk = self.work / "fixture.apk"
        with zipfile.ZipFile(self.apk, "w") as archive:
            archive.writestr("classes.dex", make_dex())
            archive.writestr("classes2.dex", make_static_field_dex())
        self.out = self.work / "out"

    def run_cli(self, *args):
        return subprocess.run(
            [sys.executable, str(ROOT / "main.py"), "batch", str(self.apk), *args],
            cwd=ROOT,
            capture_output=True,
            text=True,
            timeout=60,
        )

    def run_getclass(self, name):
        return subprocess.run(
            [sys.executable, str(ROOT / "main.py"), "getclass", str(self.apk), name],
            cwd=ROOT,
            capture_output=True,
            text=True,
            timeout=60,
        )

    def write_class_list(self, *lines):
        listing = self.work / "classes.txt"
        listing.write_text("\n".join(lines) + "\n", encoding="utf-8")
        return listing

    def test_from_file_accepts_dotted_and_dalvik_names(self):
        listing = self.write_class_list(
            "# generated by listclass",
            "example.Test",
            "Lexample/Statics;",
            "",
        )
        result = self.run_cli("--from-file", str(listing), "-o", str(self.out))
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertTrue((self.out / "example" / "Test.java").is_file())
        self.assertTrue((self.out / "example" / "Statics.java").is_file())

    def test_prefix_decompiles_every_matching_class(self):
        result = self.run_cli("--prefix", "example", "-o", str(self.out))
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual(
            sorted(p.name for p in (self.out / "example").glob("*.java")),
            ["Statics.java", "Test.java"],
        )

    def test_cli_output_matches_getclass_output(self):
        result = self.run_cli("--prefix", "example", "-o", str(self.out))
        self.assertEqual(result.returncode, 0, result.stderr)

        expected = self.run_getclass("example.Test")
        self.assertEqual(expected.returncode, 0, expected.stderr)

        written = (self.out / "example" / "Test.java").read_text(encoding="utf-8")
        # getclass prints the source, so its stdout carries one extra newline.
        self.assertEqual(written.rstrip("\n"), expected.stdout.rstrip("\n"))
        self.assertTrue(written.endswith("\n"))

    def test_empty_prefix_is_a_clean_error(self):
        result = self.run_cli("--prefix", "", "-o", str(self.out))
        self.assertEqual(result.returncode, 1)
        self.assertIn("Class prefix cannot be empty", result.stderr)

    def test_missing_class_warns_but_writes_the_rest(self):
        listing = self.write_class_list("example.Test", "example.Ghost")
        result = self.run_cli("--from-file", str(listing), "-o", str(self.out))
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertIn("1 class(es) not in APK", result.stderr)
        self.assertTrue((self.out / "example" / "Test.java").is_file())
        self.assertFalse((self.out / "example" / "Ghost.java").exists())

    def test_no_listed_class_present_is_an_error(self):
        listing = self.write_class_list("example.Ghost")
        result = self.run_cli("--from-file", str(listing), "-o", str(self.out))
        self.assertEqual(result.returncode, 1)
        self.assertIn("None of the listed classes are present", result.stderr)

    def test_empty_class_list_is_a_clean_error(self):
        listing = self.write_class_list("# only a comment")
        result = self.run_cli("--from-file", str(listing), "-o", str(self.out))
        self.assertEqual(result.returncode, 1)
        self.assertIn("no class names found", result.stderr)

    def test_resume_skips_existing_output(self):
        result = self.run_cli("--prefix", "example", "-o", str(self.out))
        self.assertEqual(result.returncode, 0, result.stderr)

        target = self.out / "example" / "Test.java"
        target.write_text("// edited\n", encoding="utf-8")

        resumed = self.run_cli("--prefix", "example", "-o", str(self.out), "--resume")
        self.assertEqual(resumed.returncode, 0, resumed.stderr)
        self.assertEqual(target.read_text(encoding="utf-8"), "// edited\n")

    def test_final_summary_reports_counts(self):
        result = self.run_cli("--prefix", "example", "-o", str(self.out))
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertIn("[BATCH] done written=2 skipped=0 failed=0", result.stderr)

    def test_limit_caps_the_selection(self):
        result = self.run_cli("--prefix", "example", "-o", str(self.out), "--limit", "1")
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual(len(list(self.out.rglob("*.java"))), 1)


if __name__ == "__main__":
    unittest.main()
